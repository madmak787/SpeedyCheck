import { formatSpeed, type SpeedUnit } from "@/lib/speed-utils"

type HistoryResult = {
  downloadSpeed: number
  uploadSpeed: number
  latency: number
  jitter: number
  packetLoss?: number
  timestamp: number
}

const PAGE_W = 595
const PAGE_H = 842

const escapePdf = (value: string) => value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)")

const formatWhen = (timestamp: number) =>
  new Date(timestamp).toLocaleString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  })

const toUnit = (mbps: number, unit: SpeedUnit) => (unit === "bytes" ? mbps / 8 : mbps)

const buildPdf = (content: string) => {
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>`,
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ]

  let body = "%PDF-1.4\n"
  const offsets = [0]
  objects.forEach((object, index) => {
    offsets.push(body.length)
    body += `${index + 1} 0 obj\n${object}\nendobj\n`
  })

  const xrefStart = body.length
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (let i = 1; i <= objects.length; i += 1) {
    body += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`
  }
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`
  return new Blob([body], { type: "application/pdf" })
}

export const buildHistoryComparePdf = (results: HistoryResult[], unit: SpeedUnit) => {
  const sorted = [...results].sort((a, b) => a.timestamp - b.timestamp)
  const baseline = sorted[0]
  const newest = sorted[sorted.length - 1]
  const speedLabel = unit === "bytes" ? "MB/s" : "Mbps"
  const lines = [
    "0.06 0.06 0.06 rg",
    "0 0 595 842 re f",
    "0.25 0.86 0.84 rg",
    "36 802 72 6 re f",
    "BT",
    "/F1 22 Tf",
    "0.96 0.96 0.96 rg",
    "36 768 Td",
    "(SpeedyCheck) Tj",
    "0 -18 Td",
    "/F1 11 Tf",
    "0.6 0.6 0.6 rg",
    "(Selected result comparison) Tj",
    "0 -14 Td",
    "/F1 9 Tf",
    `(${escapePdf(`${sorted.length} tests · ${speedLabel} · change is newest vs oldest`)}) Tj`,
    "ET",
  ]

  const headers = ["When", "Download", "Upload", "Ping", "Jitter", "Loss"]
  const cols = [36, 176, 256, 336, 408, 480]
  let y = 700
  headers.forEach((header, index) => {
    lines.push(`BT /F1 8 Tf 0.25 0.86 0.84 rg ${cols[index]} ${y} Td (${header}) Tj ET`)
  })
  y -= 8
  lines.push(`0.25 0.86 0.84 RG 36 ${y} 523 0.5 re S`)
  y -= 20

  sorted.forEach((result) => {
    const down = formatSpeed(result.downloadSpeed, unit)
    const up = formatSpeed(result.uploadSpeed, unit)
    const values = [
      formatWhen(result.timestamp),
      `${down.value} ${down.unit}`,
      `${up.value} ${up.unit}`,
      `${result.latency} ms`,
      `${result.jitter} ms`,
      `${result.packetLoss ?? 0}%`,
    ]
    values.forEach((value, index) => {
      lines.push(`BT /F1 8 Tf 0.95 0.95 0.95 rg ${cols[index]} ${y} Td (${escapePdf(value)}) Tj ET`)
    })
    y -= 18
  })

  y -= 12
  lines.push(`BT /F1 11 Tf 0.25 0.86 0.84 rg 36 ${y} Td (Change vs oldest selected) Tj ET`)
  y -= 20

  const row = (label: string, current: number, start: number, suffix: string, invert = false) => {
    const diff = current - start
    const better = invert ? diff < 0 : diff > 0
    const sign = diff > 0 ? "+" : ""
    const note = Math.abs(diff) < 0.05 ? "unchanged" : better ? "improved" : "declined"
    lines.push(
      `BT /F1 9 Tf 0.78 0.78 0.78 rg 36 ${y} Td (${escapePdf(`${label}: ${sign}${diff.toFixed(1)} ${suffix} (${note})`)}) Tj ET`,
    )
    y -= 16
  }

  row("Download", toUnit(newest.downloadSpeed, unit), toUnit(baseline.downloadSpeed, unit), speedLabel)
  row("Upload", toUnit(newest.uploadSpeed, unit), toUnit(baseline.uploadSpeed, unit), speedLabel)
  row("Ping", newest.latency, baseline.latency, "ms", true)
  row("Jitter", newest.jitter, baseline.jitter, "ms", true)
  row("Loss", newest.packetLoss ?? 0, baseline.packetLoss ?? 0, "%", true)

  y -= 8
  lines.push(`BT /F1 8 Tf 0.45 0.45 0.45 rg 36 ${y} Td (Generated by SpeedyCheck) Tj ET`)

  return buildPdf(lines.join("\n") + "\n")
}

const isAbort = (error: unknown) => error instanceof DOMException && error.name === "AbortError"

export const shareHistoryComparePdf = async (results: HistoryResult[], unit: SpeedUnit) => {
  const blob = buildHistoryComparePdf(results, unit)
  const file = new File([blob], "speedycheck-compare.pdf", { type: "application/pdf" })

  try {
    if (typeof navigator.canShare === "function" && navigator.canShare({ files: [file] })) {
      await navigator.share({ files: [file], title: "SpeedyCheck comparison" })
      return "shared" as const
    }
  } catch (error) {
    if (isAbort(error)) return "cancelled" as const
  }

  const href = URL.createObjectURL(blob)
  const link = document.createElement("a")
  link.href = href
  link.download = "speedycheck-compare.pdf"
  document.body.appendChild(link)
  link.click()
  link.remove()
  window.setTimeout(() => URL.revokeObjectURL(href), 1500)
  return "downloaded" as const
}
